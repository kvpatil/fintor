"""Regenerate the embedded font faces in .streamlit/config.toml.

Run: python -m src.web_app.fonts

The woff2 files under static/fonts/ are the source of truth; the base64 in
config.toml is generated output. Two things forced this shape:

1. Streamlit 1.60's own app-static route returns HTTP 500 here - its gzip
   middleware raises "Expected ASGI message 'http.response.start'" - so
   url = "app/static/fonts/..." does not work. Data URIs ride in the theme
   payload instead, which is sent once per session rather than per rerun.
2. The serif is declared as "Fintor Serif", not "Source Serif 4". Streamlit
   bundles a family called "Source Serif" and SILENTLY DROPS a declared face
   whose name collides with it - verified in the browser, the face never
   reached document.fonts at all.
"""

from __future__ import annotations

import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / ".streamlit" / "config.toml"
FONT_DIR = Path(__file__).resolve().parent / "static" / "fonts"

# (declared family, file, weight range). Both are variable fonts, so one file
# per family spans every weight.
FACES = [
    ("Inter Tight", "inter-tight-variable.woff2", "100 900"),
    ("Fintor Serif", "source-serif-4-variable.woff2", "200 900"),
]

HEADER = """# --- type ---------------------------------------------------------------
# GENERATED by `python -m src.web_app.fonts` - do not hand-edit the base64.
# Source of truth: src/web_app/static/fonts/*.woff2
#
# Embedded as data URIs because Streamlit 1.60's app-static route 500s here
# (gzip middleware: "Expected ASGI message 'http.response.start'"). The theme
# payload is sent once per session, so this costs nothing per rerun.
#
# "Fintor Serif" IS Source Serif 4, aliased: Streamlit bundles "Source Serif"
# and silently drops a declared face whose family name collides with it.

"""


def build_block() -> str:
    blocks = []
    for family, filename, weight in FACES:
        data = base64.b64encode((FONT_DIR / filename).read_bytes()).decode("ascii")
        blocks.append(
            f'[[theme.fontFaces]]\nfamily = "{family}"\nweight = "{weight}"\n'
            f'style = "normal"\nurl = "data:font/woff2;base64,{data}"\n'
        )
    return HEADER + "\n".join(blocks) + "\n"


def main() -> int:
    text = CONFIG.read_text(encoding="utf-8")
    start = text.index("# --- type ---")
    end = text.index("[theme]\n")
    CONFIG.write_text(text[:start] + build_block() + text[end:], encoding="utf-8")
    for family, filename, _ in FACES:
        size = (FONT_DIR / filename).stat().st_size
        print(f"  {family:14s} {filename:32s} {size:>6d}B embedded")
    print(f"  config.toml now {CONFIG.stat().st_size // 1024}KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
