"""Emit docs/demo-script.md - the teleprompter cut.

Generated from narration.toml and the measured clips so the timings are the
real ones, not estimates. This is what makes re-recording in a human voice
practical: each beat carries the duration it has to land in.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from record_demo import AUDIO, load_beats, probe_seconds  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "demo-script.md"
FINAL_CUT = ROOT / "docs" / "demo.mp4"

WHAT_IS_ON_SCREEN = {
    "01-signin": "Sign-in screen, the six demo accounts, then signing in as **dev**.",
    "02-first-answer": "Chat. *How concentrated is my portfolio?* The status widget "
                       "reports each node as it completes, then the cited answer.",
    "03-same-question": "Sign out, sign in as **walter**, ask *Should I buy more NVDA?*",
    "04-fanout": "*How are capital gains taxed and how is SPY doing?* Two agents run.",
    "05-portfolio": "Portfolio tab: allocation bar, holdings table, correlation heatmap.",
    "06-market": "Market tab: quotes, price with moving averages, stat tiles, "
                 "indexed comparison.",
    "07-goals": "Goals tab: the plan inputs, the projection, the scenario table.",
    "08-internals": "AI Internals, scrolling: routing, retrieval ranks, model calls, trace.",
    "09-close": "About Fintor, then the Architecture page.",
}


def main() -> int:
    beats, voice, rate = load_beats()
    for i, b in enumerate(beats, 1):
        clip = AUDIO / f"{i:02d}-{b.id}.aiff"
        b.seconds = probe_seconds(clip) if clip.exists() else 0.0

    total = sum(b.seconds + b.pause_after for b in beats)
    lines = [
        "# Fintor — demo narration script",
        "",
        *headline(total, len(beats)),
        "",
        "Generated from `scripts/narration.toml`; the beat durations are measured "
        "from the rendered reference clips, not estimated. Do not edit this file by "
        "hand — edit the TOML and re-run `scripts/write_script.py`.",
        "",
        "## Recording it yourself",
        "",
        "The footage is already cut to these timings, so you do not have to match them "
        "exactly — but the closer you land, the less drift at the end.",
        "",
        "1. Record each beat as its own file, named `NN-<id>.m4a`, into "
        "`build/demo/audio/` (replacing the synthetic clips), **or** record one "
        "continuous take.",
        "2. Re-run the mux:",
        "",
        "   ```",
        "   # per-beat files already in place",
        "   .venv/bin/python scripts/mux_demo.py",
        "",
        "   # or one continuous take",
        "   .venv/bin/python scripts/mux_demo.py --audio path/to/narration.m4a",
        "   ```",
        "",
        "The video is never re-recorded. Only the audio is replaced.",
        "",
        "This writes `build/demo/demo_mux.mp4`, not the file the app plays. "
        "The committed `docs/demo.mp4` is a copy of the finished mix from "
        "`scripts/remix.py`; replacing it is a deliberate step, not a "
        "side effect of re-running the mux.",
        "",
        "---",
        "",
    ]

    at = 0.0
    for i, b in enumerate(beats, 1):
        span = b.seconds + b.pause_after
        start, end = at, at + span
        at = end
        words = len(b.text.split())
        lines += [
            f"## {i}. `{b.id}`",
            "",
            f"**{fmt(start)} – {fmt(end)}**  ·  {span:.0f}s  ·  {words} words  "
            f"·  ~{words/max(span,1)*60:.0f} wpm",
            "",
            f"*On screen:* {WHAT_IS_ON_SCREEN.get(b.id, '—')}",
            "",
            "> " + b.text.replace(". ", ".\n> "),
            "",
        ]

    lines += [
        "---",
        "",
        f"Synthetic reference track: macOS `say`, voice **{voice}**, {rate} wpm.",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}  ({total/60:.2f} min of reference narration, "
          f"{sum(len(b.text.split()) for b in beats)} words)")
    return 0


def headline(total: float, n_beats: int) -> list[str]:
    """The runtime, and why it is not the sum of the beats below.

    Two different things get measured on this page and the header used to
    report only the second as though it were the first:

      * `total` sums the SYNTHETIC reference clips - macOS `say` at the rate in
        narration.toml - over the nine beats. It is a guide for anyone
        re-recording, which is what this document is for.
      * The shipped cut is built from the ElevenLabs narration instead
        (narration_build.py), which is paced differently, then trimmed by
        assemble_final.py. Nothing forces the two to agree and they do not:
        9.64 min of reference against a 9:22 film.

    Reporting the reference sum as "N minutes" read as the runtime and
    contradicted the README. So measure the film for the runtime and label the
    reference as a reference.
    """
    if FINAL_CUT.exists():
        shipped = probe_seconds(FINAL_CUT)
        head = (f"**{mmss(shipped)}** finished runtime, measured from "
                f"`{FINAL_CUT.relative_to(ROOT)}`. The brief asks for 5–10 minutes.")
    else:
        # A clean clone has the film; a working copy mid-render might not.
        head = ("Finished runtime unknown — `docs/demo.mp4` is not present. "
                "The brief asks for 5–10 minutes.")
    return [
        head,
        "",
        f"The {n_beats} beat timings below total {total/60:.2f} min and come from the "
        "synthetic reference track, which is paced differently from the voice that "
        "shipped. Treat them as relative targets for a re-recording, not as clock "
        "positions in the finished film.",
    ]


def mmss(seconds: float) -> str:
    """Rounded, unlike fmt(): 561.99s is 9:22, which is what the README says.

    fmt() truncates, which is right for cumulative beat boundaries - a beat
    starts when the previous one ends - but would print this film as 9:21.
    """
    s = round(seconds)
    return f"{s//60}:{s%60:02d}"


def fmt(seconds: float) -> str:
    return f"{int(seconds)//60}:{int(seconds)%60:02d}"


if __name__ == "__main__":
    raise SystemExit(main())
